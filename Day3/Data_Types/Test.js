// Javascript is a dynamically typed language, which means that you don't have to declare the data type of a variable when you create it. The data type is determined automatically based on the value assigned to the variable.

// Here are some examples of different data types in JavaScript:

let data=10; //number
console.log(typeof data); // Output: number

data="Ram Marshivane"; //string
console.log(typeof data); // Output: string

console.log(data); // Output: Ram Marshivane

